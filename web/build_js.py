"""Bundle web/src/*.js into web/mcgen.js and export the generator data (palettes, block options)
to web/mcgen_data.json. Run from the project root:  python web/build_js.py"""
import json, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from mcgen.palettes import PALETTES
from mcgen.house import DEFAULT_SPEC
from mcgen.colors import OPTIONS, WORDS, BLOCKS

HERE = os.path.dirname(os.path.abspath(__file__))
# Files whose top-level code needs another file's constants at load time go here, in that order.
# Any other web/src/*.js is picked up automatically (appended in alphabetical order), so adding a new
# module never means editing this file — and two branches that each add a file never conflict here.
ORDER = [
    "py.js",
    "core.js",
    "house.js",
    "layout.js",
    "api.js",
    "terrain.js",
    "props.js",
    "stall.js",
    "fountain.js",
    "monument.js",
    "matslots.js",
    "church.js",
    "gothic.js",
    "gothic_styles.js",
    "cathedral.js",
    "landmark.js",
    "site.js",
    "district.js",
    "town.js",
]


def sources():
    found = sorted(f for f in os.listdir(os.path.join(HERE, "src")) if f.endswith(".js"))
    return [f for f in ORDER if f in found] + [f for f in found if f not in ORDER]


# Everything declared at the top level of a source file (function / class / const NAME) is exported, so a
# new module never has to edit a shared export list either. Names starting with "_" stay private.
TOP = re.compile(r"^(?:async\s+)?(?:function\*?|class|const|let)\s+([A-Za-z$][\w$]*)", re.M)


def exports(src):
    names = []
    for n in TOP.findall(src):
        if n not in names and n != "api":
            names.append(n)
    return names


def data():
    opts = {s: [{"key": o["key"], "cls": o["cls"], "hex": o["hex"], "roles": o["roles"], "lab": list(o["lab"])} for o in v]
            for s, v in OPTIONS.items()}
    cn = {o["key"]: BLOCKS[o["key"]]["cn"] for v in OPTIONS.values() for o in v}
    return {"palettes": PALETTES, "options": opts, "words": WORDS, "default_spec": DEFAULT_SPEC, "cn": cn}


def bundle():
    src = "\n".join(open(os.path.join(HERE, "src", f), encoding="utf-8").read() for f in sources())
    names = exports(src)
    return ("/* mcgen.js — Minecraft house generator (JavaScript port of the mcgen Python package).\n"
            "   Generated by web/build_js.py from web/src/*.js; edit the sources, not this file. */\n"
            "(function (root) {\n'use strict';\n" + src +
            "\nconst api = { " + ", ".join(names) + ",\n"
            " _py: { PyRandom, deriveSeed, _h, pyRound, fmt } };\n"
            "if (typeof module === 'object' && module.exports) module.exports = api; else root.MCGen = api;\n"
            "})(typeof globalThis !== 'undefined' ? globalThis : this);\n")


if __name__ == "__main__":
    open(os.path.join(HERE, "mcgen.js"), "w", encoding="utf-8").write(bundle())
    json.dump(data(), open(os.path.join(HERE, "mcgen_data.json"), "w", encoding="utf-8"), ensure_ascii=False, separators=(",", ":"))
    print("web/mcgen.js", os.path.getsize(os.path.join(HERE, "mcgen.js")), "bytes;",
          "web/mcgen_data.json", os.path.getsize(os.path.join(HERE, "mcgen_data.json")), "bytes")
